def records(s):
    ll=s.splitlines(keepends=True)
    prompts=[i for i,v in enumerate(ll) if v.strip()=="## Prompt:"]
    responses=[i for i,v in enumerate(ll) if v.strip()=="## Response:"]
    if len(prompts)!=118 or len(responses)!=116 or len(ll)!=12997:
        raise ValueError("unexpected session III export structure")
    rows=[]
    for n,p in enumerate(prompts,1):
        end=prompts[n] if n<len(prompts) else len(ll)
        r=next((i for i in responses if p<i<end),None)
        user="".join(ll[p+2:r if r is not None else end]).strip()
        source="".join(ll[r+2:end]).strip() if r is not None else ""
        timings=list(re.finditer(r"Обработка заняла \d+(?:m\s*\d+s|s)",source))
        gm=source[timings[-1].end():].strip() if timings else source
        heading=TOP.search(gm)
        if heading: gm=gm[heading.start():].strip()
        cut=gm.find("**Ход Шики.**")
        if cut!=-1:gm=gm[:cut+len("**Ход Шики.**")].strip()
        ref=f"archive/session-003-source.md#L{p+1}-L{end}"
        rows.append(dict(n=n,p=p,e=end,r=r,user=user,gm=gm,
                         source=source,ref=ref))
    return ll,rows

def original_input(rec):
    user=rec["user"]
    # The exact unedited user input remains in the original source archive.
    idx=re.search(r"(?:По игре:|по игре:)\s*",user)
    if idx:return user[idx.end():].strip()
    if user.casefold().startswith("мастеру:") or user.startswith("+ введение"):
        hashes=re.search(r"(?:^|\n)\s*(#[^#\n]{3,}#.*)$",user,re.M)
        return hashes.group(1).strip() if hashes else ""
    if user.lower().startswith("#мастеру:"):
        return ""
    return user

def normalize_clock(v):
    if v.count(":")==1:return v+":00"
    return v

def end_time(rec,prev):
    n=rec["n"]
    if n==39:return "0006-09-27T06:03:00"
    if n==116:return FINAL_AT
    lines=rec["gm"].splitlines()
    samples=[]
    for line in lines[-25:]:
        m=CLOCK.match(line.strip())
        if m:samples.append(m.group(1))
    clock=samples[-1] if samples else None
    if not clock:
        start=TOP.search(rec["gm"])
        if start:
            first=TIME_HEAD.search(start.group())
            if first:clock=first.group()
    if not clock: return prev
    day=27 if n>=39 else 26
    at=f"0006-09-{day:02}T{normalize_clock(clock)}"
    if at<prev:
        print("NON_MONOTONE_SOURCE_TIME",n,at,"=>",prev,flush=True)
        return prev
    return at

