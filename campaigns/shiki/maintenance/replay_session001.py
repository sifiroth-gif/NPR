def replay(source_dir: Path, destination: Path) -> dict:
    src = source_dir / "campaign.sqlite"
    manifest = json.loads((source_dir / "state.json").read_text(encoding="utf-8"))
    game = Campaign(src)
    before = game.verify()
    if manifest != {"format": FORMAT, **before, "sha256": file_sha256(src)}:
        raise RuntimeError("Existing campaign manifest differs from verified SQLite; aborting")
    if before["campaign_id"] != "naruto-shiki" or before["revision"] != 0 or not before["pending"]:
        raise RuntimeError(f"Unexpected live campaign: {before}; refuse to overwrite")
    initial = game.context(audience="gm", recent=0)
    if initial["pending"]["turn_id"] != "opening.001":
        raise RuntimeError("Not the approved pending opening.001")
    if initial["pending"]["packet"] is None:
        raise RuntimeError("opening.001 is not prepared")
    if "Рейго" not in initial["pending"]["packet"]["text"]:
        raise RuntimeError("opening.001 content unexpected")
    working = destination / "session1-working.sqlite"
    shutil.copyfile(src, working)
    campaign = Campaign(working)
    start = campaign.context(audience="gm", recent=0)
    receipt = campaign.confirm("opening.001", start["pending"]["draft_sha"])
    assert receipt["revision"] == 1, receipt
    for number, turn in enumerate(TURNS, 2):
        packet = {
            "id": turn["id"],
            "expected_revision": number - 1,
            "at": at(turn["time"]),
            "location": turn.get("location", HALL),
            "player_input": turn["input"],
            "input_mode": "in_character",
            "text": SOURCE + "\n\n" + turn["text"],
            "events": turn["events"],
        }
        prepared = campaign.prepare(packet)
        if prepared["status"] != "prepared":
            raise RuntimeError(f"Unexpected packet state: {prepared['status']}")
        confirmed = campaign.confirm(turn["id"], prepared["draft_sha"])
        if confirmed["revision"] != number:
            raise RuntimeError(f"Replay revision mismatch: {confirmed}")
    info = campaign.verify()
    expected = len(TURNS) + 1
    if (info["revision"] != expected or info["pending"]
        or info["instance"] != before["instance"] or info["session"] != 1
        or info["at"] != at("14:21")):
        raise RuntimeError(f"Checkpoint validation failed: {info}")
    ctx = campaign.context(audience="gm", recent=50)
    if len(ctx["recent"]) != expected:
        raise RuntimeError("Replayed turn count mismatch")
    if ctx["recent"][-1]["id"] != "s01.010":
        raise RuntimeError("Final played turn mismatch")
    final = destination / "campaign.sqlite"
    checked = campaign.checkpoint(final)
    second = Campaign(final).verify()
    if {k:v for k,v in checked.items() if k not in ("sha256","path")} != second:
        raise RuntimeError("Post-backup verify mismatch")
    output = {"format": FORMAT, **second, "sha256": file_sha256(final)}
    (destination / "state.json").write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    assert output["instance"] == manifest["instance"]
    assert output["revision"] == expected and output["pending"] is False
    return output

if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("Usage: python -m campaigns.shiki.maintenance.replay_session001 STATE_DIR OUTPUT_DIR")
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    print(json.dumps(replay(Path(sys.argv[1]), out), ensure_ascii=False, sort_keys=True))
