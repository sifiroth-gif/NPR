_BOX = re.compile(r"<box\b.*?</box>", re.S)
_TAG = re.compile(r"<[^>\n]{1,200}>")
_SENTENCE = re.compile(r"[^.!?…\n]+[.!?…]*")
_WORD = re.compile(r"[A-Za-zА-Яа-яЁё]+(?:-[A-Za-zА-Яа-яЁё]+)*")


def _segments(text):
    """Делит текст на абзацы повествования и реплики. Вставные документы не проверяются."""
    text = _TAG.sub("", _BOX.sub("", text))
    for block in re.split(r"\n\s*\n", text):
        for raw in block.split("\n"):
            line = raw.strip().strip("*_ ").strip()
            if not line:
                continue
            kind = D if raw.lstrip("*_ ").startswith(("—", "–", "- ")) else N
            yield kind, line


def _quote(line, start, end, limit=170):
    for match in _SENTENCE.finditer(line):
        if match.start() <= start < match.end():
            sentence = match.group().strip()
            if len(sentence) <= limit:
                return sentence
            break
    left = max(0, start - 60)
    return ("…" if left else "") + line[left:min(len(line), end + 80)].strip() + "…"


def lint(text):
    hits, words, seen = [], 0, set()
    neg = 0
    for kind, line in _segments(text or ""):
        words += len(_WORD.findall(line))
        if kind == N:
            neg += len(_NEG_PARALLEL.findall(line))
        for rule, scope, weight, pattern in RULES:
            if scope != A and scope != kind:
                continue
            for match in pattern.finditer(line):
                quote = _quote(line, match.start(), match.end())
                if (rule, quote) in seen:
                    continue
                seen.add((rule, quote))
                hits.append({"rule": rule, "weight": weight, "where": kind, "quote": quote})
    per_1000 = 1000 / max(words, 1)
    if words >= 150 and neg * per_1000 > NEG_PARALLEL_PER_1000:
        hits.append({"rule": "neg_parallel", "weight": 2, "where": N,
                     "quote": f"{neg} конструкций «не X, а Y» на {words} слов"})
    hits.sort(key=lambda h: -h["weight"])
    by_rule = {}
    for hit in hits:
        by_rule[hit["rule"]] = by_rule.get(hit["rule"], 0) + 1
    score = round(sum(h["weight"] for h in hits) * per_1000, 1) if words else 0.0
    verdict = "чисто" if score < 4 else ("шум" if score < 12 else "переписать")
    return {"words": words, "score": score, "verdict": verdict, "by_rule": by_rule, "hits": hits,
            "advice": {rule: ADVICE[rule] for rule in by_rule}}


def render(report):
    lines = [f"Слов: {report['words']}. Балл: {report['score']} на 1000 слов. Вердикт: {report['verdict']}."]
    for rule, count in sorted(report["by_rule"].items(), key=lambda item: -item[1]):
        lines.append(f"\n[{rule}] × {count}. {ADVICE[rule]}")
        lines += [f"  · {h['quote']}" for h in report["hits"] if h["rule"] == rule][:8]
    return "\n".join(lines)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    as_json = "--json" in argv
    paths = [a for a in argv if not a.startswith("--")]
    text = open(paths[0], encoding="utf-8").read() if paths else sys.stdin.read()
    report = lint(text)
    print(json.dumps(report, ensure_ascii=False, indent=1) if as_json else render(report))
    return 0


