"""Исследование Шики не затягивается приёмом «нужен ещё один документ».

Ведущий охраняет тайну привычным жестом: доступ получен, часы потрачены, а в
конце сцены — изъятый лист, недостающее приложение, указатель на другой архив.
Один раз это находка. Два исследовательских хода подряд — затягивание
(s08.text.060–062). Код замечает такую концовку и делает полноту следующего
исследования обязательной: источник выдаёт то, что в нём есть.
"""
from __future__ import annotations

import re

RESEARCH = re.compile(r"(изуч|исслед|ищу\b|ищет|просматр|прочита|читаю|архив|документ|выписк|данные о|"
                      r"сведени|материал|разреш\w* кагэ|доступ к)", re.I)
DOC = (r"(лист|приложени|документ|страниц|том\b|папк|запис|журнал|отч[её]т|протокол|дел[оа]\b|"
       r"единиц\w* хранения|фонд|свит)")
DEFER = re.compile(
    r"изъят\w*|недостающ\w*|вырван\w*|можно запросить|по номеру|указател\w* на|номер\w* (?:приложени|единиц)"
    r"|(?:ещё|еще) (?:один|одна|одно) (?:документ|лист|архив|приложени|том)|продолжени\w+ (?:не было|отсутств)"
    r"|передан\w* в (?:другое|другой|отдел|ведомств|архив|хранени)"
    r"|отсутств\w*(?=[^.]{0,40}" + DOC + r")|" + DOC + r"[^.]{0,40}отсутств\w*", re.I)
TAIL = 0.6          # концовка сцены: последние 40% текста
STALL = 2           # столько исследовательских ходов подряд с такой концовкой — затягивание


def deferrals(gm):
    text = str(gm or "")
    return [m.group(0) for m in DEFER.finditer(text[int(len(text) * TAIL):])]


def track(hot, turn):
    """Обновляет серию; возвращает замечание kind=inquiry при затягивании."""
    if turn.get("kind") == "ooc" or not RESEARCH.search(str(turn.get("player") or "")):
        return []
    state = hot.setdefault("fold", {}).setdefault("inquiry", {"streak": []})
    found = deferrals(turn.get("gm"))
    if not found:
        state["streak"] = []
        return []
    state["streak"] = (state.get("streak") or [])[-3:] + [turn["id"]]
    if len(state["streak"]) < STALL:
        return []
    return [{"turn": turn["id"], "kind": "inquiry", "text":
             f"Исследование Шики {len(state['streak'])} хода подряд кончается недостающим документом "
             f"({', '.join(state['streak'])}: «{found[0]}»). Это затягивание. Следующий ход исследования "
             "выдаёт всё, что есть в доступных источниках, полностью; отсутствующее больше не откладывает ответ. "
             "Нет записанного truth — определи его сейчас по канону и запиши в d.truth."}]


def must(hot):
    streak = ((hot.get("fold") or {}).get("inquiry") or {}).get("streak") or []
    if len(streak) < STALL:
        return []
    return ["Исследование: ответ из доступных источников — целиком, без нового «недостающего листа» "
            f"(затягивание в {', '.join(streak[-STALL:])})."]
